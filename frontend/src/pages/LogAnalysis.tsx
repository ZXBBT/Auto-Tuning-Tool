import { useEffect, useMemo, useState } from 'react'
import { Line, LineChart, ReferenceArea, ResponsiveContainer } from 'recharts'
import { api, type Analysis, type Sample } from '../api'
import { grid, tip, xAxis, yAxis } from '../components/axes'
import { ChartCard, Legend } from '../components/charts'
import { C, margin } from '../components/theme'
import { ErrorBox, PageIntro, Severity, Slider, Tile } from '../components/ui'

const CATEGORY_ORDER = ['knock', 'fueling', 'boost', 'timing', 'general']

type Row = Record<string, number | null>

export default function LogAnalysis() {
  const [samples, setSamples] = useState<Sample[]>([])
  const [source, setSource] = useState<{ kind: 'sample'; id: string } | { kind: 'file'; file: File } | null>(null)
  const [octane, setOctane] = useState(98)
  const [result, setResult] = useState<Analysis | null>(null)
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [dragOver, setDragOver] = useState(false)

  useEffect(() => {
    api.samples().then((s) => {
      setSamples(s)
      if (s.length) setSource({ kind: 'sample', id: s[0].id })
    }, (e) => setError(String(e.message ?? e)))
  }, [])

  useEffect(() => {
    if (!source) return
    let stale = false
    setBusy(true)
    setError(null)
    const req = source.kind === 'sample' ? api.sampleAnalysis(source.id, octane) : api.analyzeUpload(source.file, octane)
    req.then(
      (r) => { if (!stale) setResult(r) },
      (e) => { if (!stale) { setError(e.message); setResult(null) } },
    ).finally(() => { if (!stale) setBusy(false) })
    return () => { stale = true }
  }, [source, octane])

  const rows: Row[] = useMemo(() => {
    if (!result) return []
    const s = result.series
    const n = s.time_s?.length ?? 0
    return Array.from({ length: n }, (_, i) => {
      const r: Row = {}
      for (const k of Object.keys(s)) r[k] = s[k][i]
      const kr = [1, 2, 3, 4].map((c) => s[`knock_retard_cyl${c}`]?.[i] ?? 0)
      r.knock_max = Math.max(...kr.map((v) => v ?? 0))
      return r
    })
  }, [result])

  const onFile = (file: File | undefined) => {
    if (!file) return
    if (file.size > 5 * 1024 * 1024) { setError('File is larger than 5 MB.'); return }
    setSource({ kind: 'file', file })
  }

  const stats = useMemo(() => {
    if (!result || !rows.length) return null
    const boost = rows.map((r) => r.boost_kpa ?? 0)
    const knockSamples = rows.filter((r) => (r.knock_max ?? 0) > 0.5).length
    return { peakBoost: Math.max(...boost) / 100, knockSamples }
  }, [result, rows])

  const wot = result?.wot
  const shade = wot ? <ReferenceArea x1={wot.t_start} x2={wot.t_end} fill="var(--accent)" fillOpacity={0.06} ifOverflow="extendDomain" /> : null
  const tLabel = (t: number) => `t = ${t.toFixed(2)} s`

  return (
    <>
      <PageIntro title="Log analysis">
        Upload a COBB Accessport CSV, or pick a sample. Dynamis maps the channels onto a standard schema, finds the
        wide-open-throttle pull, and reports bottlenecks: knock, fueling, boost, and how much timing the physics model
        thinks is left.
      </PageIntro>

      <div className="grid-side">
        <div className="card">
          <h3>Log source</h3>
          <p className="sub">Synthetic samples are generated by the engine model.</p>
          {samples.map((s) => (
            <button
              key={s.id}
              className="choice"
              aria-pressed={source?.kind === 'sample' && source.id === s.id}
              onClick={() => setSource({ kind: 'sample', id: s.id })}
            >
              <b>{s.title}</b>
              <span>{s.detail}</span>
            </button>
          ))}
          <label
            className={dragOver ? 'dropzone over' : 'dropzone'}
            onDragOver={(e) => { e.preventDefault(); setDragOver(true) }}
            onDragLeave={() => setDragOver(false)}
            onDrop={(e) => { e.preventDefault(); setDragOver(false); onFile(e.dataTransfer.files[0]) }}
          >
            <input type="file" accept=".csv,text/csv" onChange={(e) => onFile(e.target.files?.[0])} />
            <b>{source?.kind === 'file' ? source.file.name : 'Upload a COBB CSV'}</b>
            <span>Drop a file here or click to choose. Max 5 MB.</span>
          </label>
          <div className="divider" />
          <Slider label="Fuel octane (RON)" value={octane} min={91} max={104} step={1} onChange={setOctane}
                  hint="Used by the knock model for the timing-headroom estimate." />
        </div>

        <div className="stack">
          <ErrorBox message={error} />
          {busy && !result && <div className="card empty">Analyzing…</div>}
          {result && stats && (
            <>
              <div className="tiles" style={{ opacity: busy ? 0.6 : 1 }}>
                <Tile label="WOT pull" value={result.wot_rpm ? `${Math.round(result.wot_rpm[0])}–${Math.round(result.wot_rpm[1])}` : '—'} unit="rpm"
                      note={`${result.qa.rows} rows · ${result.qa.sample_rate_hz ?? '?'} Hz`} />
                <Tile label="Peak boost" value={stats.peakBoost.toFixed(2)} unit="bar" note="gauge pressure" />
                <Tile label="Knock-retard samples" value={stats.knockSamples} note="> 0.5° on any cylinder" />
                <Tile label="Power left on the table" value={`~${Math.round(result.est_power_left_hp)}`} unit="hp" note="model estimate" />
              </div>

              <div className="card">
                <h3>Findings</h3>
                <p className="sub">
                  <span className="tag">observed</span> comes straight from logged channels.{' '}
                  <span className="tag model">model</span> is estimated by the physics model and carries its uncertainty.
                </p>
                <ul className="findings">
                  {[...result.findings]
                    .sort((a, b) => CATEGORY_ORDER.indexOf(a.category) - CATEGORY_ORDER.indexOf(b.category))
                    .map((f, i) => (
                      <li className="finding" key={i}>
                        <Severity level={f.severity} />
                        <div>
                          <div className="msg">{f.message}</div>
                          <div className="tags">
                            <span className="tag">{f.category}</span>
                            <span className={f.source === 'observed' ? 'tag' : 'tag model'}>{f.source === 'observed' ? 'observed' : 'model'}</span>
                          </div>
                        </div>
                      </li>
                    ))}
                </ul>
              </div>

              <div className="grid-2">
                <ChartCard title="Engine speed" sub="Shaded: detected WOT pull">
                  <ResponsiveContainer>
                    <LineChart data={rows} margin={margin}>
                      {grid()}
                      {shade}
                      {xAxis({ dataKey: 'time_s', unit: ' s' })}
                      {yAxis({ width: 52 })}
                      {tip({ xLabel: tLabel, series: [{ key: 'rpm', label: 'RPM', color: C.s1, digits: 0 }] })}
                      <Line dataKey="rpm" stroke={C.s1} strokeWidth={2} dot={false} isAnimationActive={false} />
                    </LineChart>
                  </ResponsiveContainer>
                </ChartCard>

                <ChartCard title="Boost pressure" sub="Gauge, kPa">
                  <ResponsiveContainer>
                    <LineChart data={rows} margin={margin}>
                      {grid()}
                      {shade}
                      {xAxis({ dataKey: 'time_s', unit: ' s' })}
                      {yAxis({  })}
                      {tip({ xLabel: tLabel, series: [{ key: 'boost_kpa', label: 'Boost', color: C.s1, unit: 'kPa', digits: 0 }] })}
                      <Line dataKey="boost_kpa" stroke={C.s1} strokeWidth={2} dot={false} isAnimationActive={false} />
                    </LineChart>
                  </ResponsiveContainer>
                </ChartCard>

                <ChartCard
                  title="Ignition timing & knock retard"
                  sub="Degrees. Retard is timing the ECU pulled after detecting knock."
                  legend={<Legend items={[{ label: 'Ignition (°BTDC)', color: C.s1 }, { label: 'Knock retard, worst cyl (°)', color: C.s2 }]} />}
                >
                  <ResponsiveContainer>
                    <LineChart data={rows} margin={margin}>
                      {grid()}
                      {shade}
                      {xAxis({ dataKey: 'time_s', unit: ' s' })}
                      {yAxis({ unit: '°' })}
                      {tip({ xLabel: tLabel, series: [
                        { key: 'ignition_deg', label: 'Ignition', color: C.s1, unit: '°' },
                        { key: 'knock_max', label: 'Knock retard', color: C.s2, unit: '°' },
                      ] })}
                      <Line dataKey="ignition_deg" stroke={C.s1} strokeWidth={2} dot={false} isAnimationActive={false} />
                      <Line dataKey="knock_max" stroke={C.s2} strokeWidth={2} dot={false} isAnimationActive={false} />
                    </LineChart>
                  </ResponsiveContainer>
                </ChartCard>

                <ChartCard
                  title="Lambda: actual vs target"
                  sub="Below 1 is rich. Rich mixtures cool the charge and suppress knock."
                  legend={<Legend items={[{ label: 'Actual', color: C.s1 }, { label: 'Target', color: C.s2, kind: 'dash' }]} />}
                >
                  <ResponsiveContainer>
                    <LineChart data={rows} margin={margin}>
                      {grid()}
                      {shade}
                      {xAxis({ dataKey: 'time_s', unit: ' s' })}
                      {yAxis({ domain: [0.75, 1.05], ticks: [0.8, 0.9, 1.0], fmt: (v) => v.toFixed(2) })}
                      {tip({ xLabel: tLabel, series: [
                        { key: 'lambda', label: 'Actual', color: C.s1, digits: 3 },
                        { key: 'lambda_target', label: 'Target', color: C.s2, digits: 3 },
                      ] })}
                      <Line dataKey="lambda" stroke={C.s1} strokeWidth={2} dot={false} isAnimationActive={false} />
                      <Line dataKey="lambda_target" stroke={C.s2} strokeWidth={2} strokeDasharray="5 4" dot={false} isAnimationActive={false} />
                    </LineChart>
                  </ResponsiveContainer>
                </ChartCard>
              </div>

              <details className="card">
                <summary style={{ cursor: 'pointer', fontWeight: 600 }}>Plain-text report (same as the CLI)</summary>
                <pre className="mono" style={{ whiteSpace: 'pre-wrap', margin: '12px 0 0' }}>{result.report_text}</pre>
              </details>
            </>
          )}
        </div>
      </div>
    </>
  )
}
